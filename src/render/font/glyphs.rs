fn uppercase(ch: char) -> char {
    match ch {
        'á' => 'Á',
        'à' => 'À',
        'â' => 'Â',
        'ã' => 'Ã',
        'ç' => 'Ç',
        'é' => 'É',
        'ê' => 'Ê',
        'í' => 'Í',
        'ó' => 'Ó',
        'ô' => 'Ô',
        'õ' => 'Õ',
        'ú' => 'Ú',
        _ => ch.to_ascii_uppercase(),
    }
}

#[cfg(test)]
mod tests {
    use super::glyph;

    #[test]
    fn includes_letters_used_by_the_display() {
        assert_eq!(
            glyph('P'),
            [0b11110, 0b10001, 0b10001, 0b11110, 0b10000, 0b10000, 0b10000]
        );
        assert_ne!(glyph('Z'), glyph('?'));
    }

    #[test]
    fn normalizes_lowercase_and_uppercase_accents() {
        assert_eq!(glyph('ã'), glyph('Ã'));
        assert_eq!(glyph('â'), glyph('Â'));
        assert_eq!(glyph('é'), glyph('É'));
        assert_eq!(glyph('ç'), glyph('Ç'));
    }
}
